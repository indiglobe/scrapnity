/* ============================================================
 * SCRAP COLLECTION STATUS
 * ============================================================ */

export function SCRAP_COLLECTION_STATUS() {
  return [
    "order-placed",
    "payment-processing",
    "order-accepted",
    "process-completed",
  ] as const;
}

export function scrapCollectionStatusEnum(
  columnName = "scrap_collection_status",
) {
  return mysqlEnum(columnName, SCRAP_COLLECTION_STATUS());
}

/* ============================================================
 * PRICE UNIT
 * ============================================================ */

export function PRICE_UNIT() {
  return ["piece", "kilo"] as const;
}

export function priceUnitEnum(columnName = "price_unit") {
  return mysqlEnum(columnName, PRICE_UNIT());
}

/* ============================================================
 * CREATED AT
 * ============================================================ */

export function createdAt(columnName = "created_at") {
  return timestamp(columnName, {
    mode: "date",
    fsp: 6,
  })
    .$defaultFn(() => new Date())
    .notNull();
}

/* ============================================================
 * UPDATED AT
 * ============================================================ */

export function updatedAt(columnName = "updated_at") {
  return timestamp(columnName, {
    mode: "date",
    fsp: 6,
  })
    .$defaultFn(() => new Date())
    .$onUpdate(() => new Date())
    .notNull();
}

/* ============================================================
 * METADATA
 * ============================================================ */

export function metadata(token: TableIdentifierToken) {
  return {
    createdAt: createdAt(),
    updatedAt: updatedAt(),
    tableIdentifierToken: tokenColumn(token),
  };
}

/* ============================================================
 * TABLE IDENTIFIER TOKEN COLUMN
 * ============================================================ */

export function tableIdentifierToken(columnName = "table_identifier_token") {
  return mysqlEnum(columnName, [
    "SCIT",
    "VUSE",
    "CUSE",
    "SPIN",
    "SCLP",
    "STAT",
    "DIST",
    "PAYM",
    "VSCI",
  ] as [TableIdentifierToken, ...TableIdentifierToken[]]);
}

export function tokenColumn(token: TableIdentifierToken) {
  return tableIdentifierToken().notNull().default(token);
}

/* ============================================================
 * ID HELPERS
 * ============================================================ */

/**
 * Generates a 9-character uppercase ID.
 *
 * Example:
 *   A81F3C921
 */
export function autogeneratedId() {
  return char("id", {
    length: 9,
  })
    .primaryKey()
    .notNull()
    .$defaultFn(() =>
      crypto.randomUUID().replaceAll("-", "").toUpperCase().slice(0, 9),
    );
}

/**
 * Foreign keys use the exact same format as autogeneratedId().
 */
export function foreignId(columnName: string) {
  return char(columnName, {
    length: 9,
  });
}

/* ============================================================
 * COMMON COLUMN HELPERS
 * ============================================================ */

export function phoneNumberColumn(columnName = "phone_number") {
  return char(columnName, {
    length: 10,
  }).notNull();
}

export function pinCodeColumn(columnName = "pin_code") {
  return char(columnName, {
    length: 6,
  }).notNull();
}

