import {
  mysqlTable,
  mysqlEnum,
  char,
  timestamp,
  varchar,
  int,
  datetime,
  primaryKey,
  uniqueIndex,
} from "drizzle-orm/mysql-core";
import { relations } from "drizzle-orm";

/* ============================================================
 * USERS
 * ============================================================ */

/**
 * Vendors who collect scrap from customers.
 */
export const Table__VendorUser = mysqlTable("vendor_user", {
  id: autogeneratedId(),
  email: varchar("email", { length: 255 }).notNull().unique(),
  name: varchar("name", { length: 255 }).notNull(),
  phoneNumber: phoneNumberColumn("phone_number"),
  aadhaarNumber: char("aadhaar_number", { length: 12 }).notNull(),
  address: varchar("address", { length: 255 }).notNull(),
  city: varchar("city", { length: 255 }).notNull(),
  district: varchar("district", { length: 255 }).notNull(),
  state: varchar("state", { length: 255 }).notNull(),
  pinCode: pinCodeColumn("pin_code"),

  ...metadata("VUSE"),
});

/**
 * Customers who request scrap collection.
 */
export const Table__CustomerUser = mysqlTable("customer_user", {
  id: autogeneratedId(),
  email: varchar("email", { length: 255 }).notNull().unique(),
  name: varchar("name", { length: 255 }).notNull(),
  phoneNumber: phoneNumberColumn(),
  address: varchar("address", { length: 255 }).notNull(),
  pinCode: pinCodeColumn("pin_code"),

  ...metadata("CUSE"),
});

/* ============================================================
 * SCRAP ITEMS
 * ============================================================ */

export const Table__ScrapItem = mysqlTable("scrap_item", {
  id: autogeneratedId(),
  productName: varchar("product_name", { length: 255 }).notNull().unique(),
  vendorPrice: int("vendor_price").notNull(),
  customerPrice: int("customer_price").notNull(),
  priceUnit: priceUnitEnum().notNull(),
  commisionRate: int("commision_rate")
    .notNull()
    .$defaultFn(() => 10),

  ...metadata("SCIT"),
});

/* ============================================================
 * VENDOR <-> SCRAP ITEM
 * ============================================================ */

export const Table__VendorScrapItem = mysqlTable(
  "vendor_scrap_item",
  {
    vendorId: foreignId("vendor_id")
      .notNull()
      .references(() => Table__VendorUser.id, {
        onDelete: "cascade",
        onUpdate: "cascade",
      }),
    scrapItemId: foreignId("scrap_item_id")
      .notNull()
      .references(() => Table__ScrapItem.id, {
        onDelete: "cascade",
        onUpdate: "cascade",
      }),

    ...metadata("VSCI"),
  },
  (table) => [
    primaryKey({
      columns: [table.vendorId, table.scrapItemId],
    }),
  ],
);

/* ============================================================
 * VENDOR SERVICEABLE PINCODES
 * ============================================================ */

export const Table__ServiceablePincode = mysqlTable(
  "serviceable_pincode",
  {
    vendorId: foreignId("vendor_id")
      .notNull()
      .references(() => Table__VendorUser.id, {
        onDelete: "cascade",
        onUpdate: "cascade",
      }),
    pinCode: pinCodeColumn("pin_code"),

    ...metadata("SPIN"),
  },
  (table) => [
    primaryKey({
      columns: [table.vendorId, table.pinCode],
    }),
  ],
);

/* ============================================================
 * SCRAP COLLECTION ORDERS
 * ============================================================ */

export const Table__ScrapCollectionProcess = mysqlTable(
  "scrap_collection_process",
  {
    id: autogeneratedId(),
    customerId: foreignId("customer_id")
      .notNull()
      .references(() => Table__CustomerUser.id, {
        onDelete: "cascade",
        onUpdate: "cascade",
      }),
    vendorId: foreignId("vendor_id").references(() => Table__VendorUser.id, {
      onDelete: "set null",
      onUpdate: "cascade",
    }),
    scrapItemId: foreignId("scrap_item_id")
      .notNull()
      .references(() => Table__ScrapItem.id, {
        onDelete: "restrict",
        onUpdate: "cascade",
      }),
    floor: varchar("floor", { length: 50 }).notNull(),
    landmark: varchar("landmark", { length: 255 }).notNull(),
    collectionDateTime: datetime("collection_date_time").notNull(),
    status: scrapCollectionStatusEnum("scrap_collection_status")
      .notNull()
      .$defaultFn(() => "order-placed"),

    ...metadata("SCLP"),
  },
);

/* ============================================================
 * PAYMENTS
 * ============================================================ */

/**
 * Payment information for a scrap collection order.
 */
export const Table__Payment = mysqlTable(
  "payment",
  {
    id: autogeneratedId(),
    vendorId: foreignId("vendor_id")
      .notNull()
      .references(() => Table__VendorUser.id, {
        onDelete: "cascade",
        onUpdate: "cascade",
      }),
    scrapOrderId: foreignId("scrap_order_id")
      .notNull()
      .references(() => Table__ScrapCollectionProcess.id, {
        onDelete: "cascade",
        onUpdate: "cascade",
      }),
    razorpayOrderId: varchar("razorpay_order_id", {
      length: 255,
    }).notNull(),
    razorpayPaymentId: varchar("razorpay_payment_id", {
      length: 255,
    }),
    razorpaySignature: varchar("razorpay_signature", {
      length: 255,
    }),

    ...metadata("PAYM"),
  },
  (table) => [
    uniqueIndex("payment_razorpay_order_id_idx").on(table.razorpayOrderId),
  ],
);

/* ============================================================
 * STATES
 * ============================================================ */

export const Table__State = mysqlTable("state", {
  id: varchar("id", { length: 255 }).notNull().primaryKey(),
  stateName: varchar("state_name", { length: 255 }).notNull().unique(),

  ...metadata("STAT"),
});

/* ============================================================
 * DISTRICTS
 * ============================================================ */

/**
 * District belonging to a state.
 */
export const Table__District = mysqlTable("district", {
  id: varchar("id", { length: 255 }).notNull().primaryKey(),
  districtName: varchar("district_name", { length: 255 }).notNull(),
  associatedState: varchar("associated_state", { length: 255 })
    .notNull()
    .references(() => Table__State.id, {
      onDelete: "cascade",
      onUpdate: "cascade",
    }),

  ...metadata("DIST"),
});

